"""Console summary tables and Markdown benchmark report generation."""

import json
import os
import platform
from datetime import datetime

from .memory_guard import format_size_gb, resolve_memory_limit_bytes


def write_cli_markdown_report(output_file: str, report_path: str, mode: str) -> None:
    """Render a standalone Markdown report file from the completed JSON results."""
    if not (output_file and os.path.exists(output_file)):
        return
    try:
        with open(output_file) as f:
            data = json.load(f)
        configs = data.get("configs", data.get("results", []))
        os.makedirs(os.path.dirname(report_path) or ".", exist_ok=True)
        with open(report_path, "w") as f:
            f.write("# Longbow Performance Report\n\n")
            f.write(f"**Generated**: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}  \n")
            f.write(f"**Mode**: {mode}  \n")
            f.write(f"**Configs**: {len(configs)}  \n\n")
            f.write("## Results\n\n")
            f.write("| Dim | Dtype | Count | Search Mode | QPS | P50 (ms) | P95 (ms) | P99 (ms) | Ingest (vec/s) | Index Time (s) |\n")
            f.write("|-----|-------|-------|-------------|-----|----------|----------|----------|----------------|----------------|\n")
            for cfg in configs:
                dim = cfg.get("dim", "?")
                dtype = cfg.get("dtype", "?")
                count = cfg.get("count", "?")
                ingest = cfg.get("ingest", {}).get("vec_per_sec", 0)
                idx_time = cfg.get("ingest", {}).get("indexing_duration_seconds", 0)
                idx_str = f"{idx_time:.2f}s" if idx_time > 0 else "-"
                for m_name, s_data in cfg.get("search", {}).items():
                    f.write(
                        f"| {dim} | {dtype} | {count} | {m_name} "
                        f"| {s_data.get('qps', 0):.1f} "
                        f"| {s_data.get('p50', 0):.3f} "
                        f"| {s_data.get('p95', 0):.3f} "
                        f"| {s_data.get('p99', 0):.3f} "
                        f"| {ingest:.1f} "
                        f"| {idx_str} |\n"
                    )
            f.write("\n---\n\n")
            f.write("*Report generated by unified_benchmark.py*\n")
        print(f"\n  [report] Generated Markdown report at {report_path}")
    except Exception as e:
        print(f"\n  [report] ERROR: {e}")


