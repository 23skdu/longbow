LONGBOW_META_ADDR=0.0.0.0:3001 \
LONGBOW_METRICS_ADDR=0.0.0.0:9090 \
LONGBOW_GOSSIP_ENABLED=true \
LONGBOW_GOSSIP_PORT=7946 \
LONGBOW_GOSSIP_ADVERTISE_ADDR=127.0.0.1 \
LONGBOW_NODE_ID=node1 \
LONGBOW_DATA_PATH=./data/node1 \
LONGBOW_MAX_MEMORY=8589934592 \
LONGBOW_GPU_ENABLED=true \
./bin/longbow-metal > node1.log 2>&1 &
echo $! > node1.pid

sleep 2

echo "Starting Node 2..."
LONGBOW_LISTEN_ADDR=0.0.0.0:3100 \
LONGBOW_META_ADDR=0.0.0.0:3101 \
LONGBOW_METRICS_ADDR=0.0.0.0:9190 \
LONGBOW_GOSSIP_ENABLED=true \
