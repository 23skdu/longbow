// dot32FMA computes dot product of exactly 32 float32s using AVX-512 FMA.
// a, b are pointers to 128-byte buffers (32 × 4 bytes).
TEXT ·dot32FMA(SB), NOSPLIT, $0-20
	MOVQ  a+0(FP), AX
	MOVQ  b+8(FP), CX

	VXORPS Z0, Z0, Z0

	VMOVUPS (AX), Z1
	VMOVUPS (CX), Z2
	VFMADD231PS Z1, Z2, Z0

	VMOVUPS 64(AX), Z1
	VMOVUPS 64(CX), Z2
	VFMADD231PS Z1, Z2, Z0

	VEXTRACTF64X4 $0x00, Z0, Y1
	VEXTRACTF64X4 $0x01, Z0, Y0
	VADDPS Y1, Y0, Y0

	VEXTRACTF128 $0x00, Y0, X1
	VEXTRACTF128 $0x01, Y0, X0
	VADDPS X1, X0, X0

	VMOVHLPS X0, X3, X3
	VADDPS X3, X0, X0

	VMOVSHDUP X0, X1
	VADDSS X1, X0, X0

	MOVSS X0, ret+16(FP)
	VZEROUPPER
	RET

