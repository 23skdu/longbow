	MOVQ  b+8(FP), CX

	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2
	VXORPS Z3, Z3, Z3

	VMOVUPS (AX), Z4
	VMOVUPS (CX), Z5
	VFMADD231PS Z4, Z5, Z0

	VMOVUPS 64(AX), Z4
	VMOVUPS 64(CX), Z5
	VFMADD231PS Z4, Z5, Z1

	VMOVUPS 128(AX), Z4
	VMOVUPS 128(CX), Z5
	VFMADD231PS Z4, Z5, Z2

	VMOVUPS 192(AX), Z4
	VMOVUPS 192(CX), Z5
	VFMADD231PS Z4, Z5, Z3

	VADDPS Z1, Z0, Z0
	VADDPS Z3, Z2, Z2
	VADDPS Z2, Z0, Z0

	VEXTRACTF64X4 $0x00, Z0, Y1
	VEXTRACTF64X4 $0x01, Z0, Y0
	VADDPS Y1, Y0, Y0

	VEXTRACTF128 $0x00, Y0, X1
