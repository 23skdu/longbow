LONGBOW_DATA_PATH=./data/node2 \
LONGBOW_MAX_MEMORY=8589934592 \
LONGBOW_GPU_ENABLED=true \
./bin/longbow-metal > node2.log 2>&1 &
echo $! > node2.pid

