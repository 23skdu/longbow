// cosine32FMA computes dot product and squared norms for exactly 32 float32s.
// Returns (dot, normA, normB).
TEXT ·cosine32FMA(SB), NOSPLIT, $0-28
	MOVQ  a+0(FP), AX
	MOVQ  b+8(FP), CX

	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2

	VMOVUPS (AX), Z3
	VMOVUPS (CX), Z4
	VFMADD231PS Z3, Z4, Z0
	VFMADD231PS Z3, Z3, Z1
	VFMADD231PS Z4, Z4, Z2

	VMOVUPS 64(AX), Z3
	VMOVUPS 64(CX), Z4
	VFMADD231PS Z3, Z4, Z0
	VFMADD231PS Z3, Z3, Z1
	VFMADD231PS Z4, Z4, Z2

	// Reduce Z0 (dot)
	VEXTRACTF64X4 $0x00, Z0, Y3
	VEXTRACTF64X4 $0x01, Z0, Y4
	VADDPS Y3, Y4, Y4
	VEXTRACTF128 $0x00, Y4, X3
	VEXTRACTF128 $0x01, Y4, X4
	VADDPS X3, X4, X4
	VMOVHLPS X4, X3, X3
	VADDPS X3, X4, X4
	VMOVSHDUP X4, X3
	VADDSS X3, X4, X4
	MOVSS X4, dot+16(FP)

	// Reduce Z1 (normA)
	VEXTRACTF64X4 $0x00, Z1, Y3
	VEXTRACTF64X4 $0x01, Z1, Y4
	VADDPS Y3, Y4, Y4
	VEXTRACTF128 $0x00, Y4, X3
	VEXTRACTF128 $0x01, Y4, X4
	VADDPS X3, X4, X4
	VMOVHLPS X4, X3, X3
	VADDPS X3, X4, X4
	VMOVSHDUP X4, X3
	VADDSS X3, X4, X4
	MOVSS X4, normA+20(FP)

	// Reduce Z2 (normB)
	VEXTRACTF64X4 $0x00, Z2, Y3
	VEXTRACTF64X4 $0x01, Z2, Y4
	VADDPS Y3, Y4, Y4
	VEXTRACTF128 $0x00, Y4, X3
	VEXTRACTF128 $0x01, Y4, X4
	VADDPS X3, X4, X4
	VMOVHLPS X4, X3, X3
	VADDPS X3, X4, X4
	VMOVSHDUP X4, X3
	VADDSS X3, X4, X4
	MOVSS X4, normB+24(FP)

	VZEROUPPER
	RET

// cosineDotAVX512 computes dot product and squared norms for arbitrary-length float32 vectors.
// Uses ZMM registers processing 16 elements per iteration.
TEXT ·cosineDotAVX512(SB), NOSPLIT, $0-36
	MOVQ  a+0(FP), AX
	MOVQ  b+8(FP), CX
	MOVQ  n+16(FP), DX

	VXORPS Z0, Z0, Z0
	VXORPS Z1, Z1, Z1
	VXORPS Z2, Z2, Z2

loop:
	CMPQ  DX, $16
	JL    tail
	VMOVUPS (AX), Z3
	VMOVUPS (CX), Z4
	VFMADD231PS Z3, Z4, Z0
	VFMADD231PS Z3, Z3, Z1
	VFMADD231PS Z4, Z4, Z2
	ADDQ  $64, AX
	ADDQ  $64, CX
	SUBQ  $16, DX
	JMP   loop

