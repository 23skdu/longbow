LONGBOW_GOSSIP_ADVERTISE_ADDR=127.0.0.1 \
LONGBOW_GOSSIP_STATIC_PEERS=127.0.0.1:7946 \
LONGBOW_NODE_ID=node3 \
LONGBOW_DATA_PATH=./data/node3 \
LONGBOW_MAX_MEMORY=8589934592 \
